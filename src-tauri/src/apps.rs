//! Todas las aplicaciones del PC (las del menú Inicio), con su icono.
//! Algunas son juegos de tiendas que la consola no lee directamente (EA, Ubisoft, Riot,
//! Rockstar, Battle.net, itch, Amazon…): esas pasan a la biblioteca solas.
//! El usuario puede corregirlo: "Marcar como juego" o "No es un juego".

use crate::games::Game;
use serde::{Deserialize, Serialize};
use std::path::PathBuf;
use std::process::Command;

#[derive(Serialize, Clone, Debug)]
#[serde(rename_all = "camelCase")]
pub struct App {
    pub id: String,
    pub name: String,
    /// Icono en PNG (ruta local), si se pudo sacar
    pub icon: Option<String>,
    /// Herramienta de Windows (Símbolo del sistema, Servicios…): se enseñan aparte
    pub system: bool,
    #[serde(skip)]
    pub app_id: String,
}

/// Identificador estable (FNV-1a): no cambia entre versiones, así las marcas se conservan
pub fn stable_id(s: &str) -> String {
    let mut h: u64 = 0xcbf29ce484222325;
    for b in s.to_lowercase().bytes() {
        h ^= u64::from(b);
        h = h.wrapping_mul(0x100000001b3);
    }
    format!("{h:016x}")
}

/// Nombre simplificado para comparar ("The Witcher® 3" = "the witcher 3")
pub fn norm(s: &str) -> String {
    s.chars().filter(|c| c.is_alphanumeric()).flat_map(char::to_lowercase).collect()
}

// ---------- Qué es un juego ----------

/// Carpetas y enlaces típicos de juegos instalados por cualquier tienda
const GAME_HINTS: &[&str] = &[
    "steamapps", "steam://rungameid", "com.epicgames.launcher://apps", "\\epic games\\", "gog galaxy\\games",
    "\\gog games\\", "ubisoft game launcher\\games", "uplay://launch", "\\ea games\\", "origin games", "\\riot games\\",
    "xboxgames", "\\rockstar games\\", "\\itch\\apps\\", "amazon games\\library", "battlenet://", "\\games\\",
];
/// Las tiendas en sí son aplicaciones, no juegos
const LAUNCHERS: &[&str] = &[
    "steam", "epic games launcher", "ea", "ea app", "origin", "ubisoft connect", "uplay", "battle.net", "gog galaxy",
    "riot client", "rockstar games launcher", "amazon games", "itch", "xbox", "game bar", "playnite", "heroic",
];

pub fn looks_like_game(name: &str, app_id: &str) -> bool {
    let id = app_id.to_lowercase();
    let n = name.trim().to_lowercase();
    !LAUNCHERS.contains(&n.as_str()) && GAME_HINTS.iter().any(|h| id.contains(h))
}

/// Accesos que no son programas: desinstaladores, webs, manuales…
fn is_junk(name: &str, app_id: &str) -> bool {
    let n = name.to_lowercase();
    let id = app_id.to_lowercase();
    const WORDS: &[&str] = &["uninstall", "desinstalar", "documentation", "readme", "léame", "manual", "website", "sitio web", "get help", "visit ", "release notes", "license"];
    const EXT: &[&str] = &[".url", ".html", ".htm", ".chm", ".txt", ".pdf", ".md"];
    WORDS.iter().any(|w| n.contains(w))
        || id.starts_with("http://")
        || id.starts_with("https://")
        || EXT.iter().any(|e| id.ends_with(e))
        || id == "es.consola.app"
}

/// Programas de la carpeta de Windows (System32, SysWOW64, Windows) y consolas de administración
fn is_system(app_id: &str) -> bool {
    let id = app_id.to_uppercase();
    ["{1AC14E77-02E7-4E5D-B744-2EB1AE5198B7}", "{D65231B0-B2F1-4857-A4CE-A8E7C6EA7D27}", "{F38BF404-1D43-42F2-9305-67DE0B28FC23}", "MICROSOFT.AUTOGENERATED."]
        .iter()
        .any(|p| id.starts_with(p))
        || id.ends_with(".MSC")
        || id.starts_with("MICROSOFT.WINDOWS.ADMINISTRATIVETOOLS")
}

// ---------- Marcas del usuario ----------

#[derive(Serialize, Deserialize, Default)]
pub struct Marks {
    /// Ids marcados como juego
    #[serde(default)]
    pub juegos: Vec<String>,
    /// Ids marcados como "no es un juego"
    #[serde(default)]
    pub apps: Vec<String>,
}

fn data_dir() -> PathBuf {
    let base = std::env::var("LOCALAPPDATA").unwrap_or_else(|_| ".".into());
    PathBuf::from(base).join("Consola")
}

pub fn load_marks() -> Marks {
    std::fs::read_to_string(data_dir().join("marcas.json")).ok().and_then(|t| serde_json::from_str(&t).ok()).unwrap_or_default()
}

pub fn set_mark(id: &str, game: bool) -> Result<(), String> {
    let mut m = load_marks();
    m.juegos.retain(|x| x != id);
    m.apps.retain(|x| x != id);
    if game { m.juegos.push(id.into()) } else { m.apps.push(id.into()) }
    std::fs::create_dir_all(data_dir()).map_err(|e| e.to_string())?;
    std::fs::write(data_dir().join("marcas.json"), serde_json::to_string_pretty(&m).unwrap()).map_err(|e| e.to_string())
}

// ---------- Lista del menú Inicio ----------

#[derive(Deserialize)]
struct StartRaw {
    #[serde(rename = "Name")]
    name: String,
    #[serde(rename = "AppID")]
    app_id: String,
}

pub fn parse_start_apps(json: &str) -> Vec<App> {
    let t = json.trim();
    let raws: Vec<StartRaw> = if t.starts_with('[') {
        serde_json::from_str(t).unwrap_or_default()
    } else {
        serde_json::from_str::<StartRaw>(t).map(|r| vec![r]).unwrap_or_default()
    };
    let mut seen = std::collections::HashSet::new();
    raws.into_iter()
        .filter(|r| !r.name.trim().is_empty() && !is_junk(&r.name, &r.app_id))
        .filter(|r| seen.insert(r.app_id.to_lowercase()))
        .map(|r| App { id: format!("app-{}", stable_id(&r.app_id)), system: is_system(&r.app_id), name: r.name, icon: None, app_id: r.app_id })
        .collect()
}

fn start_apps() -> Vec<App> {
    use std::os::windows::process::CommandExt;
    let out = Command::new("powershell.exe")
        .args(["-NoProfile", "-NonInteractive", "-Command", "[Console]::OutputEncoding=[Text.Encoding]::UTF8; Get-StartApps | Select-Object Name, AppID | ConvertTo-Json -Compress"])
        .creation_flags(0x0800_0000)
        .output();
    out.map(|o| parse_start_apps(&String::from_utf8_lossy(&o.stdout))).unwrap_or_default()
}

pub fn launch_uri(app_id: &str) -> String {
    format!("shell:AppsFolder\\{app_id}")
}

/// Juego sacado del menú Inicio (tienda "pc")
fn as_game(a: &App) -> Game {
    Game {
        id: a.id.clone(),
        title: a.name.clone(),
        store: "pc".into(),
        install_dir: String::new(),
        cover: None,
        hero: None,
        icon: a.icon.clone(),
        last_played: None,
        size_bytes: None,
        launch: launch_uri(&a.app_id),
    }
}

/// Reparte todo en juegos y aplicaciones, teniendo en cuenta las marcas del usuario.
/// `store_games`: los que ya encontró la consola en Steam, Epic, GOG y Xbox.
pub fn split(store_games: Vec<Game>, apps: Vec<App>, marks: &Marks) -> (Vec<Game>, Vec<App>) {
    let known: std::collections::HashSet<String> = store_games.iter().map(|g| norm(&g.title)).collect();
    let mut games = Vec::new();
    let mut others = Vec::new();
    for g in store_games {
        if marks.apps.contains(&g.id) {
            others.push(App { id: g.id.clone(), name: g.title.clone(), icon: g.icon.clone(), system: false, app_id: String::new() });
        }
        games.push(g); // los de tienda se guardan siempre (para poder lanzarlos desde Aplicaciones)
    }
    games.retain(|g| !marks.apps.contains(&g.id));
    for a in apps {
        // Acceso directo a un juego que ya sale por su tienda: no repetir
        if known.contains(&norm(&a.name)) && !marks.juegos.contains(&a.id) {
            continue;
        }
        let game = marks.juegos.contains(&a.id) || (!marks.apps.contains(&a.id) && looks_like_game(&a.name, &a.app_id));
        if game { games.push(as_game(&a)) } else { others.push(a) }
    }
    others.sort_by(|a, b| a.system.cmp(&b.system).then_with(|| a.name.to_lowercase().cmp(&b.name.to_lowercase())));
    (games, others)
}

pub fn detect() -> Vec<App> {
    let mut apps = start_apps();
    icons::fill(&mut apps);
    apps
}

// ---------- Iconos (los mismos que enseña Windows) ----------

pub mod icons {
    use super::*;
    use windows::Win32::Foundation::SIZE;
    use windows::Win32::Graphics::Gdi::*;
    use windows::Win32::System::Com::{CoInitializeEx, COINIT_APARTMENTTHREADED};
    use windows::Win32::UI::Shell::*;
    use windows::core::HSTRING;

    fn dir() -> PathBuf {
        data_dir().join("iconos")
    }

    /// Pide a Windows el icono de algo (app del menú Inicio o un .exe) y lo guarda en PNG
    fn extract(parsing_name: &str, out: &std::path::Path) -> Option<()> {
        unsafe {
            let f: IShellItemImageFactory = SHCreateItemFromParsingName(&HSTRING::from(parsing_name), None).ok()?;
            let hbm = f.GetImage(SIZE { cx: 128, cy: 128 }, SIIGBF_ICONONLY | SIIGBF_BIGGERSIZEOK).ok()?;
            let result = to_png(hbm, out);
            let _ = DeleteObject(hbm.into());
            result
        }
    }

    unsafe fn to_png(hbm: HBITMAP, out: &std::path::Path) -> Option<()> {
        let mut bm = BITMAP::default();
        if unsafe { GetObjectW(hbm.into(), std::mem::size_of::<BITMAP>() as i32, Some(&mut bm as *mut _ as *mut _)) } == 0 {
            return None;
        }
        let (w, h) = (bm.bmWidth, bm.bmHeight.abs());
        let mut info = BITMAPINFO {
            bmiHeader: BITMAPINFOHEADER {
                biSize: std::mem::size_of::<BITMAPINFOHEADER>() as u32,
                biWidth: w,
                biHeight: -h, // de arriba abajo
                biPlanes: 1,
                biBitCount: 32,
                biCompression: BI_RGB.0,
                ..Default::default()
            },
            ..Default::default()
        };
        let mut px = vec![0u8; (w * h * 4) as usize];
        let dc = unsafe { CreateCompatibleDC(None) };
        let lines = unsafe { GetDIBits(dc, hbm, 0, h as u32, Some(px.as_mut_ptr() as *mut _), &mut info, DIB_RGB_COLORS) };
        let _ = unsafe { DeleteDC(dc) };
        if lines == 0 {
            return None;
        }
        let has_alpha = px.chunks(4).any(|p| p[3] != 0);
        for p in px.chunks_mut(4) {
            p.swap(0, 2); // BGRA → RGBA
            if !has_alpha {
                p[3] = 255;
            } else if p[3] > 0 && p[3] < 255 {
                // Windows da el color ya multiplicado por la transparencia
                let a = u16::from(p[3]);
                for c in &mut p[..3] {
                    *c = ((u16::from(*c) * 255) / a).min(255) as u8;
                }
            }
        }
        let file = std::fs::File::create(out).ok()?;
        let mut enc = png::Encoder::new(std::io::BufWriter::new(file), w as u32, h as u32);
        enc.set_color(png::ColorType::Rgba);
        enc.set_depth(png::BitDepth::Eight);
        enc.write_header().ok()?.write_image_data(&px).ok()
    }

    /// Icono en caché (se saca una sola vez por programa)
    pub fn get(parsing_name: &str) -> Option<String> {
        let out = dir().join(format!("{}.png", stable_id(parsing_name)));
        if !out.exists() {
            let _ = std::fs::create_dir_all(dir());
            extract(parsing_name, &out)?;
        }
        Some(out.to_string_lossy().into_owned())
    }

    /// Rellena los iconos en un hilo con COM preparado (Windows lo exige así)
    pub fn fill(apps: &mut Vec<App>) {
        let names: Vec<String> = apps.iter().map(|a| launch_uri(&a.app_id)).collect();
        let icons = std::thread::spawn(move || {
            unsafe {
                let _ = CoInitializeEx(None, COINIT_APARTMENTTHREADED);
            }
            names.iter().map(|n| get(n)).collect::<Vec<_>>()
        })
        .join()
        .unwrap_or_default();
        for (a, i) in apps.iter_mut().zip(icons) {
            a.icon = i;
        }
    }

    /// Icono para juegos de tienda sin portada (GOG por su .exe, Xbox por su app)
    pub fn fill_games(games: &mut Vec<Game>) {
        let names: Vec<Option<String>> = games
            .iter()
            .map(|g| (g.cover.is_none() && (g.launch.ends_with(".exe") || g.launch.starts_with("shell:AppsFolder"))).then(|| g.launch.clone()))
            .collect();
        let icons = std::thread::spawn(move || {
            unsafe {
                let _ = CoInitializeEx(None, COINIT_APARTMENTTHREADED);
            }
            names.iter().map(|n| n.as_deref().and_then(get)).collect::<Vec<_>>()
        })
        .join()
        .unwrap_or_default();
        for (g, i) in games.iter_mut().zip(icons) {
            if g.icon.is_none() {
                g.icon = i;
            }
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    const SAMPLE: &str = r#"[
      {"Name":"Steam","AppID":"{7C5A40EF-A0FB-4BFC-874A-C0F2E0B9FA8E}\\Steam\\Steam.exe"},
      {"Name":"Hades","AppID":"steam://rungameid/1145360"},
      {"Name":"Assassin's Creed Mirage","AppID":"{7C5A40EF-A0FB-4BFC-874A-C0F2E0B9FA8E}\\Ubisoft\\Ubisoft Game Launcher\\games\\ACM\\ACMirage.exe"},
      {"Name":"League of Legends","AppID":"C:\\Riot Games\\Riot Client\\RiotClientServices.exe"},
      {"Name":"Riot Client","AppID":"C:\\Riot Games\\Riot Client\\RiotClientServices.exe2"},
      {"Name":"Notepad++","AppID":"{6D809377-6AF0-444B-8957-A3773F02200E}\\Notepad++\\notepad++.exe"},
      {"Name":"Símbolo del sistema","AppID":"{1AC14E77-02E7-4E5D-B744-2EB1AE5198B7}\\cmd.exe"},
      {"Name":"Uninstall RustDesk","AppID":"Microsoft.AutoGenerated.{9911}"},
      {"Name":"Node.js website","AppID":"https://nodejs.org/"},
      {"Name":"Consola","AppID":"es.consola.app"},
      {"Name":"Mi juego raro","AppID":"D:\\Cosas\\raro.exe"}
    ]"#;

    fn steam_hades() -> Game {
        Game { id: "steam-1145360".into(), title: "Hades".into(), store: "steam".into(), install_dir: String::new(), cover: None, hero: None, icon: None, last_played: None, size_bytes: None, launch: "steam://rungameid/1145360".into() }
    }

    #[test]
    fn reparte_juegos_y_aplicaciones() {
        let apps = parse_start_apps(SAMPLE);
        assert_eq!(apps.len(), 8, "sin desinstaladores, webs ni la propia consola");
        let (games, others) = split(vec![steam_hades()], apps, &Marks::default());
        let titles: Vec<_> = games.iter().map(|g| g.title.as_str()).collect();
        assert_eq!(titles, ["Hades", "Assassin's Creed Mirage", "League of Legends"], "Hades no se repite");
        let names: Vec<_> = others.iter().map(|a| a.name.as_str()).collect();
        assert_eq!(names, ["Mi juego raro", "Notepad++", "Riot Client", "Steam", "Símbolo del sistema"]);
        assert!(others.last().unwrap().system);
        assert_eq!(games[1].store, "pc");
        assert!(games[1].launch.starts_with("shell:AppsFolder\\"));
    }

    #[test]
    fn marcas_del_usuario_mandan() {
        let apps = parse_start_apps(SAMPLE);
        let raro = apps.iter().find(|a| a.name == "Mi juego raro").unwrap().id.clone();
        let league = apps.iter().find(|a| a.name == "League of Legends").unwrap().id.clone();
        let marks = Marks { juegos: vec![raro], apps: vec![league, "steam-1145360".into()] };
        let (games, others) = split(vec![steam_hades()], apps, &marks);
        let titles: Vec<_> = games.iter().map(|g| g.title.as_str()).collect();
        assert_eq!(titles, ["Assassin's Creed Mirage", "Mi juego raro"]);
        assert!(others.iter().any(|a| a.name == "League of Legends"));
        assert!(others.iter().any(|a| a.id == "steam-1145360"), "un juego de Steam marcado como app pasa a Aplicaciones");
    }

    #[test]
    fn ids_estables_y_nombres() {
        assert_eq!(stable_id("Hola"), stable_id("hola"));
        assert_ne!(stable_id("a"), stable_id("b"));
        assert_eq!(norm("The Witcher® 3: Wild Hunt"), "thewitcher3wildhunt");
    }

    #[test]
    fn icono_real_de_una_app() {
        // El Bloc de notas está en cualquier Windows
        let mut apps = vec![App { id: "x".into(), name: "Bloc".into(), icon: None, system: false, app_id: "Microsoft.WindowsNotepad_8wekyb3d8bbwe!App".into() }];
        icons::fill(&mut apps);
        let p = apps[0].icon.clone().expect("debe sacar el icono");
        assert!(std::fs::metadata(&p).unwrap().len() > 200);
    }
}
